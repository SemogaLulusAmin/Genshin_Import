class Inventory {
  final String id;
  final String name;
  final String imageUrl;
  final String rarity;
  final String subtitle;
  final int quantity;
  final String itemType;

  Inventory({
    required this.id,
    required this.name,
    required this.imageUrl,
    required this.rarity,
    required this.subtitle,
    required this.quantity,
    required this.itemType,
  });
}
